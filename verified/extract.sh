#!/usr/bin/env bash
# Regenerate lean/RwlogCore from rust/src with Charon and Aeneas.
#
#   ./extract.sh           regenerate
#   ./extract.sh --check   regenerate, then fail if the result differs from
#                          what git has (this is what CI runs)
#
# Needs `charon` and `aeneas` on PATH, at the commits recorded in
# versions.env; the script refuses to run with any other. With nix:
#
#   . ./versions.env
#   nix shell "github:AeneasVerif/aeneas/$AENEAS_COMMIT#aeneas" \
#             "github:AeneasVerif/aeneas/$AENEAS_COMMIT#charon" \
#             --extra-substituters https://hacl.cachix.org \
#             --extra-trusted-public-keys hacl.cachix.org-1:FzsZ2xsByOwKwIWNPII7yMOelJNDZ12mDAj3d1eGX0c= \
#             -c ./extract.sh
set -euo pipefail
here="$(cd "$(dirname "$0")" && pwd)"
# shellcheck source=versions.env
. "$here/versions.env"

check=0
case "${1:-}" in
  "") ;;
  --check) check=1 ;;
  *) echo "usage: $0 [--check]" >&2; exit 2 ;;
esac

# Each tool reports the commit it was built from, in full or abbreviated.
require_commit() { # require_commit <tool> <reported commit> <recorded commit>
  if [[ ! "$2" =~ ^[0-9a-f]{7,40}$ || "$3" != "$2"* ]]; then
    echo "$1 reports commit '$2', versions.env records '$3'" >&2
    exit 1
  fi
}
require_commit aeneas "$(aeneas -version | sed -n 's/^aeneas //p')" "$AENEAS_COMMIT"
require_commit charon "$(charon version | sed -n 's/^.*(\(.*\))$/\1/p')" "$CHARON_COMMIT"

out="$here/lean/RwlogCore"
marker="-- THIS FILE WAS AUTOMATICALLY GENERATED BY AENEAS"

# Remove what an earlier run generated, so that a file Aeneas no longer
# produces does not stay behind. Every generated file starts with the marker.
find "$out" -type f -name '*.lean' -print0 | while IFS= read -r -d '' f; do
  if [[ "$(head -n 1 "$f")" == "$marker" ]]; then rm "$f"; fi
done

llbc="$here/rust/target/rwlog_core.llbc"
(cd "$here/rust" && charon cargo --preset=aeneas --dest-file "$llbc")
aeneas -backend lean "$llbc" -dest "$out" -split-files -no-progress-bar

if [[ "$check" == 1 ]]; then
  cd "$here"
  if [[ -n "$(git status --porcelain -- lean/RwlogCore)" ]]; then
    git status --short -- lean/RwlogCore
    git diff -- lean/RwlogCore
    echo >&2
    echo "verified/lean/RwlogCore is not what verified/rust/src translates to." >&2
    echo "Run verified/extract.sh and commit the result." >&2
    exit 1
  fi
  echo "verified/lean/RwlogCore is what verified/rust/src translates to."
fi
